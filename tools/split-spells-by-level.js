#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { SPELLS, SPELL_SCHEMA } from "../app/data/spells.js";

const SPELL_DIR = path.resolve("app/data/spells");
const AGGREGATOR_PATH = path.resolve("app/data/spells.js");

function stableStringify(value) {
  return JSON.stringify(value, null, 2);
}

function exportNameForLevel(level) {
  return `SPELLS_LEVEL_${level}`;
}

function levelFileName(level) {
  return `level${level}.js`;
}

function writeLevelFile(level, entries) {
  const exportName = exportNameForLevel(level);
  const spellLines = entries
    .map(([id, spell]) => `  ${JSON.stringify(id)}: ${JSON.stringify(spell)},`)
    .join("\n");
  const content = [
    `// app/data/spells/${levelFileName(level)}`,
    `// Generated by tools/split-spells-by-level.js. Edit spell records here, then run validation.`,
    "",
    `export const ${exportName} = {`,
    spellLines,
    `};`,
    "",
    `export default ${exportName};`,
    "",
  ].join("\n");
  fs.writeFileSync(path.join(SPELL_DIR, levelFileName(level)), content);
}

function writeAggregator(levels) {
  const imports = levels
    .map((level) => `import { ${exportNameForLevel(level)} } from "./spells/${levelFileName(level)}";`)
    .join("\n");
  const spreadLines = levels.map((level) => `  ...${exportNameForLevel(level)},`).join("\n");
  const content = `// app/data/spells.js
// Spell registry aggregator. Spell records live in app/data/spells/level*.js.
// Distances in feet unless unit === "tile". 5 ft === 1 tile.
// "dialogueRelated" marks spells that can appear as dialogue options.

${imports}

export const SPELL_SCHEMA = ${stableStringify(SPELL_SCHEMA)};

export const SPELLS = {
${spreadLines}
};

export function getSpellById(id) {
  const spell = SPELLS[id] || null;
  return spell?.active === false ? null : spell;
}

export function getSpellRecordById(id, { includeInactive = false } = {}) {
  const spell = SPELLS[id] || null;
  if (!spell) return null;
  if (!includeInactive && spell.active === false) return null;
  return spell;
}

export function isSpellActive(spell) {
  return spell?.active !== false;
}

export function listSpellsByClass(cls) {
  return Object.values(SPELLS).filter((spell) => isSpellActive(spell) && (spell.classes ?? []).includes(cls));
}
`;
  fs.writeFileSync(AGGREGATOR_PATH, content);
}

function main() {
  fs.mkdirSync(SPELL_DIR, { recursive: true });
  const grouped = new Map();
  for (const [id, spell] of Object.entries(SPELLS)) {
    if (!Number.isInteger(spell.level)) throw new Error(`${id}: spell.level must be an integer`);
    if (!grouped.has(spell.level)) grouped.set(spell.level, []);
    grouped.get(spell.level).push([id, spell]);
  }

  const levels = [...grouped.keys()].sort((a, b) => a - b);
  for (const level of levels) writeLevelFile(level, grouped.get(level));
  writeAggregator(levels);
  console.log(`[spells] Split ${Object.keys(SPELLS).length} spells across ${levels.length} level file(s).`);
}

main();
